function loadJSON(key, fallback) {
  try {
    const value = localStorage.getItem(key);
    return value === null ? fallback : JSON.parse(value);
  } catch (error) {
    return fallback;
  }
}
function normalizedWrong(value) {
  if (!value || typeof value !== 'object' || Array.isArray(value)) return {};
  return Object.fromEntries(Object.entries(value).filter(([, item]) => item && typeof item === 'object' && item.w));
}
function normalizedStats(value) {
  const data = value && typeof value === 'object' ? value : {};
  return {
    total: Number.isFinite(data.total) && data.total >= 0 ? data.total : 0,
    correct: Number.isFinite(data.correct) && data.correct >= 0 ? data.correct : 0,
    mastered: Array.isArray(data.mastered) ? [...new Set(data.mastered.filter(x => typeof x === 'string'))] : []
  };
}
let wrong = normalizedWrong(loadJSON(STORAGE_KEYS.wrong, {}));
let stats = normalizedStats(loadJSON(STORAGE_KEYS.stats, {}));
let daily = loadJSON(STORAGE_KEYS.daily, {});
if (!daily || typeof daily !== 'object' || Array.isArray(daily)) daily = {};

function save() {
  try {
    localStorage.setItem(STORAGE_KEYS.wrong, JSON.stringify(wrong));
    localStorage.setItem(STORAGE_KEYS.stats, JSON.stringify(stats));
    localStorage.setItem(STORAGE_KEYS.daily, JSON.stringify(daily));
  } catch (error) {
    console.warn('학습 기록을 저장하지 못했습니다.', error);
  }
  updateCounts();
}
function todayKey() {
  const now = new Date();
  return `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, '0')}-${String(now.getDate()).padStart(2, '0')}`;
}
function setToday() {
  const now = new Date();

  const date = new Intl.DateTimeFormat('ko-KR', {
    year: 'numeric',
    month: 'long',
    day: 'numeric'
  }).format(now);

  const weekday = new Intl.DateTimeFormat('ko-KR', {
    weekday: 'short'
  }).format(now);

  $('today').textContent = `${date} (${weekday})`;
}

function updateCounts() {
  const wrongCount = Object.keys(wrong).length;
  $('wrongCount').textContent = wrongCount;
  $('totalAnswered').textContent = stats.total;
  $('accuracy').textContent = stats.total ? `${Math.round((stats.correct / stats.total) * 100)}%` : '0%';
  $('mastered').textContent = stats.mastered.length;
  const sessions = daily[todayKey()] || 0;
  $('statsMessage').innerHTML = `지금까지 <b>${stats.total}</b>문제를 풀었습니다.<br>정답은 <b>${stats.correct}</b>번, 오늘 완료한 훈련은 <b>${sessions}</b>회입니다.<br>작전 실패 기록에는 <b>${wrongCount}</b>개 단어가 있습니다.<br>${stats.total === 0 ? '아직 훈련 기록이 없습니다. 첫 작전을 개시하겠습니다!' : '케로케로리~! 꾸준한 훈련이 실력으로 이어지는 것입니다!'}`;
}
function shuffle(items) {
  const result = [...items];
  for (let i = result.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [result[i], result[j]] = [result[j], result[i]];
  }
  return result;
}
function setActiveLevelButtons() {
  document.querySelectorAll('.level').forEach(button => {
    const active = button.dataset.level === level;
    button.classList.toggle('active', active);
    button.setAttribute('aria-pressed', String(active));
  });
}
function selectLevel(newLevel) {
  if (!bank[newLevel]) return;
  level = newLevel;
  reviewMode = false;
  setActiveLevelButtons();
  startQuiz();
}
function startQuiz() {
  currentSessionId++;
  if (reviewMode) {
    questions = shuffle(Object.values(wrong)).map(item => ({ ...item, level: item.level || level }));
  } else {
    questions = shuffle(bank[level]).slice(0, QUESTION_LIMIT).map(item => ({ ...item, level }));
  }
  index = 0;
  correctCount = 0;
  answered = false;
  $('questionArea').hidden = questions.length === 0;
  $('completeArea').hidden = questions.length !== 0;
  $('progressLabel').textContent = reviewMode ? '오답 복습 작전' : `오늘의 훈련 · ${level}`;
  $('nextButton').onclick = nextQuestion;
  $('reviewFromComplete').hidden = Object.keys(wrong).length === 0;
  updateProgress(0, questions.length);
  if (questions.length) renderQuestion();
  else showComplete();
}
function updateProgress(done, total) {
  const percent = total ? Math.round((done / total) * 100) : 0;
  $('progressCount').textContent = `${done} / ${total}`;
  $('progressBar').style.width = `${percent}%`;
  document.querySelector('.progress').setAttribute('aria-valuenow', String(percent));
}
function renderQuestion() {
  if (index >= questions.length) {
    showComplete();
    return;
  }
  const q = questions[index];
  answered = false;
  updateProgress(index, questions.length);
  $('wordBadge').textContent = `JLPT ${q.level} · 단어`;
  $('word').textContent = q.w;
  $('reading').textContent = q.r;
  $('feedback').hidden = true;
  $('nextButton').disabled = true;
  $('nextButton').textContent = '정답을 선택해 주십시오';

  // 복습 모드에서도 현재 단어의 레벨에 맞는 오답 선택지를 만듭니다.
  const levelPool = bank[q.level] || bank[level] || Object.values(bank).flat();
  const candidates = levelPool.filter(item => item.w !== q.w && item.m !== q.m);
  let distractors = shuffle(candidates).slice(0, 3);
  if (distractors.length < 3) {
    const allCandidates = Object.values(bank).flat().filter(item => item.w !== q.w && item.m !== q.m && !distractors.some(existing => existing.m === item.m));
    distractors = [...distractors, ...shuffle(allCandidates).slice(0, 3 - distractors.length)];
  }
  const options = shuffle([q, ...distractors]);
  const choices = $('choices');
  choices.replaceChildren();
  options.forEach((option, i) => {
    const button = document.createElement('button');
    button.type = 'button';
    button.className = 'choice';
    button.textContent = `${i + 1}. ${option.m}`;
    button.addEventListener('click', () => chooseAnswer(option.m, button));
    choices.appendChild(button);
  });
}
function chooseAnswer(meaning, selectedButton) {
  if (answered) return;
  answered = true;
  const q = questions[index];
  const isCorrect = meaning === q.m;
  if (isCorrect) {
    correctCount++;
    stats.correct++;
    stats.mastered = [...new Set([...stats.mastered, q.w])];
    // 정답을 맞힌 단어는 오답 기록에서 해제합니다.
    delete wrong[q.w];
  } else {
    wrong[q.w] = { ...q, level: q.level || level };
  }
  stats.total++;
  save();

document.querySelectorAll('.choice').forEach(button => {
  button.disabled = true;
  if (button.textContent.replace(/^\d+\.\s*/, '') === q.m) {
    button.classList.add('correct');
  }
});

if (!isCorrect) selectedButton.classList.add('wrong');

$('feedbackMessage').textContent = isCorrect
  ? '정답입니다! 훌륭한 성과이지 말입니다!'
  : '으으… 작전 실패입니다! 재도전하면 되는 것입니다!';

$('feedbackTitle').className = `feedback-title${isCorrect ? '' : ' bad'}`;
$('cryingKeroro').hidden = isCorrect;

$('feedbackText').innerHTML = `<b>${q.w}</b>（${q.r}）<br>뜻: ${q.m}`;
$('example').innerHTML =
  `<b>예문</b><br>${q.e}<br>` +
  `<span class="example-translation">${q.t}</span>`;

$('feedback').hidden = false;
updateProgress(index + 1, questions.length);
$('nextButton').disabled = false;
$('nextButton').textContent =
  index + 1 >= questions.length ? '훈련 결과 확인' : '다음 단어로 이동';
}
function nextQuestion() {
  if (!answered) return;
  index++;
  renderQuestion();
}
function showComplete() {
  $('questionArea').hidden = true;
  $('completeArea').hidden = false;
  $('completeTitle').textContent = questions.length ? (reviewMode ? '재훈련 작전이 종료되었습니다!' : '오늘의 작전이 종료되었습니다!') : (reviewMode ? '복습할 오답이 없습니다!' : '출제할 단어가 없습니다!');
  const accuracy = questions.length ? Math.round((correctCount / questions.length) * 100) : 0;
  $('completeText').innerHTML = questions.length
    ? `${questions.length}문제 중 <b>${correctCount}문제</b>를 맞혔습니다.<br>정답률 <b>${accuracy}%</b> — 케로케로리~! 훌륭한 훈련 성과입니다!`
    : (reviewMode ? '모든 작전 실패 기록을 정복했습니다. 훌륭합니다!' : '이 레벨에는 단어 자료가 없습니다. 다른 레벨을 선택해 주십시오.');
  $('restartButton').hidden = reviewMode;
  $('reviewFromComplete').hidden = Object.keys(wrong).length === 0;
  if (!reviewMode && questions.length) {
    daily[todayKey()] = (daily[todayKey()] || 0) + 1;
    try { localStorage.setItem(STORAGE_KEYS.daily, JSON.stringify(daily)); } catch (error) { console.warn('오늘의 기록을 저장하지 못했습니다.', error); }
    updateCounts();
  }
  updateProgress(questions.length, questions.length);
}
function showTab(tab) {
  const pages = { quiz: 'quizPage', wrong: 'wrongPage', stats: 'statsPage' };
  Object.entries(pages).forEach(([key, id]) => {
    $(id).hidden = key !== tab;
    $(`${key}Tab`).classList.toggle('active', key === tab);
    $(`${key}Tab`).setAttribute('aria-current', key === tab ? 'page' : 'false');
  });
  if (tab === 'wrong') renderWrongList();
  if (tab === 'stats') updateCounts();
}
function renderWrongList() {
  const list = $('wrongList');
  list.replaceChildren();
  const entries = Object.values(wrong).sort((a, b) => (a.level || '').localeCompare(b.level || '') || a.w.localeCompare(b.w));
  $('reviewButton').disabled = entries.length === 0;
  $('clearWrongButton').disabled = entries.length === 0;
  if (!entries.length) {
    const empty = document.createElement('div');
    empty.className = 'empty-state';
    empty.innerHTML = '아직 작전 실패 기록이 없습니다!<br>후후후… 첫 훈련에서 실력을 보여 주십시오! 케로케로리~';
    list.appendChild(empty);
    return;
  }
  entries.forEach(item => {
    const card = document.createElement('article');
    card.className = 'wrong-item';
    const head = document.createElement('div');
    head.className = 'wrong-item-head';
    const word = document.createElement('span'); word.className = 'wrong-word'; word.textContent = item.w;
    const reading = document.createElement('span'); reading.className = 'wrong-reading'; reading.textContent = item.r;
    const badge = document.createElement('span'); badge.className = 'wrong-level'; badge.textContent = `JLPT ${item.level || '—'}`;
    const meaning = document.createElement('div'); meaning.className = 'wrong-meaning'; meaning.textContent = item.m;
    head.append(word, reading, badge); card.append(head, meaning); list.appendChild(card);
  });
}
function startReview() {
  if (!Object.keys(wrong).length) return;
  reviewMode = true;
  showTab('quiz');
  startQuiz();
}
function clearWrong() {
  if (!Object.keys(wrong).length) return;
  if (!window.confirm('작전 실패 기록을 모두 비우시겠습니까?')) return;
  wrong = {};
  save();
  renderWrongList();
}

